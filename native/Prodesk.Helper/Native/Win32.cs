    public static string GetWindowTitle(IntPtr hWnd)
    {
        if (hWnd == IntPtr.Zero) return string.Empty;
        int len = GetWindowTextLength(hWnd);
        if (len <= 0) return string.Empty;
        var sb = new StringBuilder(len + 2);
        GetWindowText(hWnd, sb, sb.Capacity);
        return sb.ToString();
    }

    public static string GetWindowClass(IntPtr hWnd)
    {
        if (hWnd == IntPtr.Zero) return string.Empty;
        var sb = new StringBuilder(256);
        GetClassName(hWnd, sb, sb.Capacity);
        return sb.ToString();
    }

    public static IntPtr MakeLParam(int low, int high)
    {
        return (IntPtr)((high << 16) | (low & 0xFFFF));
    }

    public static uint GetIdleTimeMs()
    {
        var lii = new LASTINPUTINFO { cbSize = (uint)Marshal.SizeOf<LASTINPUTINFO>() };
        if (!GetLastInputInfo(ref lii)) return uint.MaxValue;
        return unchecked((uint)Environment.TickCount - lii.dwTime);
    }

    public static bool IsSecureDesktopActive()
    {
        const uint DESKTOP_READOBJECTS = 0x0001;
        const int UOI_NAME = 2;
        IntPtr hDesk = OpenInputDesktop(0, false, DESKTOP_READOBJECTS);
        if (hDesk == IntPtr.Zero)
        {
            // Cannot open input desktop -> usually UAC / Winlogon secure desktop
            return true;
        }
        try
        {
            var sb = new StringBuilder(128);
            if (GetUserObjectInformation(hDesk, UOI_NAME, sb, sb.Capacity * 2, out _))
            {
                string name = sb.ToString();
                return !string.Equals(name, "Default", StringComparison.OrdinalIgnoreCase);
            }
            return false;
        }
        finally
        {
            CloseDesktop(hDesk);
        }
    }

    public static bool IsProcessElevated(uint pid)
    {
        if (pid == 0) return false;
        const uint PROCESS_QUERY_LIMITED_INFORMATION = 0x1000;
        const uint TOKEN_QUERY = 0x0008;
        const int TokenElevation = 20;

        IntPtr hProc = OpenProcess(PROCESS_QUERY_LIMITED_INFORMATION, false, pid);
        if (hProc == IntPtr.Zero) return false;
        try
        {
            if (!OpenProcessToken(hProc, TOKEN_QUERY, out IntPtr hToken)) return false;
            try
            {
                if (GetTokenInformation(hToken, TokenElevation, out int elevated, sizeof(int), out _))
                {
                    return elevated != 0;
                }
                return false;
            }
            finally
            {
                CloseHandle(hToken);
            }
        }
        finally
        {
            CloseHandle(hProc);
        }
    }
